export function getWeeklyGuide(week: number): WeeklyGuide {
  const current = Math.max(1, Math.min(40, Math.floor(week))) - 1;
  const stage = stageForWeek(current + 1);
  return {
    development: developmentByWeek[current],
    body: bodyByStage[stage],
    feelings: feelingsByStage[stage],
    tip: weeklyTips[current],
    question: weeklyQuestions[current],
  };
}
